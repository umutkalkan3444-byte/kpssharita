/** Noktasal bir PDF hedefini yönlendirmeli soruda kullanılacak en yakın ille eşleştirir. */
export function nearestProvinceName(lat: number, lon: number): string {
  let nearestKey: keyof typeof IL = "Ankara";
  let nearestDistance = Number.POSITIVE_INFINITY;
  for (const key of Object.keys(IL) as (keyof typeof IL)[]) {
    const [provinceLat, provinceLon] = IL[key];
    // Türkiye enlemlerinde boylam farkının harita üzerindeki yatay karşılığını
    // yaklaşık olarak dengeler; amaç idari sınır hesabı değil seçenek üretimidir.
    const distance = (provinceLat - lat) ** 2 + ((provinceLon - lon) * 0.78) ** 2;
    if (distance < nearestDistance) {
      nearestDistance = distance;
      nearestKey = key;
    }
  }
  return IL_ADI[nearestKey] ?? nearestKey;
}

