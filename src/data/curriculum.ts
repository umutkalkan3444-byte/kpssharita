export const MAIN_MAP: Record<string, MainCategory> = Object.fromEntries(
  MAIN_CATEGORIES.map((m) => [m.slug, m]),
);

export type SubcategoryRef = { main: MainCategory; sub: Subcategory };

export const SUBCATEGORY_MAP: Record<string, SubcategoryRef> = (() => {
  const map: Record<string, SubcategoryRef> = {};
  for (const main of MAIN_CATEGORIES) {
    for (const sub of main.subs) {
      if (map[sub.slug]) {
        console.warn(`Duplicate subcategory slug: ${sub.slug}`);
      }
      map[sub.slug] = { main, sub };
    }
  }
  return map;
})();
