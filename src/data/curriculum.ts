export type CompassDirection = "N" | "NE" | "E" | "SE" | "S" | "SW" | "W" | "NW";

export type GameItem = {
  name: string;
  lat: number;
  lon: number;
  hint?: string;
  /** Yönlendirmeli oyunda il adını ele vermeyen soru etiketi. */
  prompt?: string;
  /** İl merkezinden uzaktaki sınır kapısı gibi hedeflerde doğru ili açıkça sabitler. */
  answerProvince?: string;
  /** Rüzgâr oyununda coğrafi nokta yerine kesin pusula yerleşimini kullanır. */
  compassDirection?: CompassDirection;
};

export type MapVariant = "provinces" | "regions" | "muted";

export type Subcategory = {
  slug: string; // uygulama genelinde benzersiz
  title: string;
  emoji?: string;
  description?: string;
  mapVariant?: MapVariant;
  items: GameItem[];
};

export type MainCategory = {
  slug: string;
  title: string;
  emoji: string;
  description: string;
  gradient: string; // tailwind gradient sınıfları
  subs: Subcategory[];
};

